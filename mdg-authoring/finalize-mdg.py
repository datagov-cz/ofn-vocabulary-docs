"""Add the real model template to an EA-generated MDG and package its XMI."""

import argparse
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET


HERE = Path(__file__).resolve().parent
REFERENCE_MDG = HERE.parent / "mdg" / "slovníkyMDG-datasets.xml"
PATTERN = HERE.parent / "mdg" / "slovníkyPattern.xml"


def finalize(mdg_path: Path) -> None:
    mdg_path = mdg_path.resolve()
    if not mdg_path.is_file():
        raise ValueError(f"MDG file does not exist: {mdg_path}")

    source_root = ET.parse(REFERENCE_MDG).getroot()
    template = source_root.find("./ModelTemplates/Model")
    if template is None or template.get("name") == "Template Name":
        raise ValueError("The reference MDG has no configured model template")
    location = template.get("location")
    if not location or Path(location).name != location:
        raise ValueError("The template location must be a filename beside the MDG")
    ET.parse(PATTERN)

    tree = ET.parse(mdg_path)
    root = tree.getroot()
    if root.tag != "MDG.Technology":
        raise ValueError("Expected an MDG.Technology XML file")
    for old in root.findall("ModelTemplates"):
        root.remove(old)
    templates = ET.SubElement(root, "ModelTemplates")
    ET.SubElement(templates, "Model", template.attrib)

    # Write only after all inputs have been checked. EA resolves this pattern
    # from the MDG folder when the files are installed together.
    tree.write(mdg_path, encoding="utf-8", xml_declaration=True)
    destination = mdg_path.parent / location
    if PATTERN.resolve() != destination.resolve():
        shutil.copy2(PATTERN, destination)
    print(f"Packaged {template.get('name')} in {mdg_path}")
    print(f"Pattern: {destination}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mdg", type=Path, help="MDG XML generated by Enterprise Architect")
    finalize(parser.parse_args().mdg)
